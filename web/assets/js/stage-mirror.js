/* =============================================================================
   THE LIVING MIRROR · the map of the Stage Path (Path III · The Stage Tower)
   A Venetian mirror broken into nine fragments (geometry: stage-mirror-data.js,
   generated by scripts/journal/stage_mirror.py). Each station of the Stage Path
   sets its fragment back into the frame; until then the gap shows a kaleidoscope
   that turns slowly and follows the finger, the mouse or the arrow keys.
   With the ninth fragment the kaleidoscope stops and the mirror shows the WHERE.
   Public API: window.StageMirror.mount(el), .refresh(), .stations
   ============================================================================= */
(function () {
  'use strict';

  var SVGNS = 'http://www.w3.org/2000/svg';
  var DATA = window.STAGE_MIRROR;
  if (!DATA) return;

  // The nine rooms of Tower III: fragment n is won by station 19 + n (map node 39 + n)
  var STATIONS = [
    { station: 20, node: 40, room: 'The Gate of a Thousand Masks', flag: 'order_masks_gate_completed' },
    { station: 21, node: 41, room: 'The Camera Obscura', flag: 'order_camera_obscura_completed' },
    { station: 22, node: 42, room: 'The Whispering Gallery', flag: 'order_whispering_gallery_completed' },
    { station: 23, node: 43, room: 'The Automaton Orchestra', flag: 'order_automaton_orchestra_completed' },
    { station: 24, node: 44, room: 'The Fly Tower', flag: 'order_fly_tower_completed' },
    { station: 25, node: 45, room: 'The Shadow Theatre', flag: 'order_shadow_theatre_completed' },
    { station: 26, node: 46, room: 'The Hall of Mirrors', flag: 'order_hall_of_mirrors_completed' },
    { station: 27, node: 47, room: 'The Kaleidoscope Lantern', flag: 'order_kaleidoscope_lantern_completed' },
    { station: 28, node: 48, room: 'The Stage of the Mirror Speaker', flag: 'order_mirror_stage_completed' }
  ];
  var SEEN_KEY = 'order_stage_mirror_seen';   // fragments already shown in place (so a new one flashes only once)
  // What the whole mirror shows at the end, kept mirror-written in this source
  var REFLECTED = 'ANNEIV · REPOSTAATS RENEIW';
  var GLASS = ['#f2c14e', '#e76f51', '#9b5de5', '#2ec4b6', '#f15bb5', '#4cc9f0', '#90be6d', '#ffb4a2', '#ffd6a5'];

  function ls(k) { try { return localStorage.getItem(k); } catch (e) { return null; } }
  function owned() { return STATIONS.map(function (s) { return ls(s.flag) === 'true'; }); }
  function reducedMotion() { return !!(window.matchMedia && window.matchMedia('(prefers-reduced-motion: reduce)').matches); }
  function el(tag, attrs, parent) {
    var n = document.createElementNS(SVGNS, tag);
    if (attrs) Object.keys(attrs).forEach(function (k) { n.setAttribute(k, attrs[k]); });
    if (parent) parent.appendChild(n);
    return n;
  }
  function pathOf(points, close) {
    return points.map(function (p, i) { return (i ? 'L' : 'M') + p[0] + ' ' + p[1]; }).join(' ') + (close ? ' Z' : '');
  }
  function glassPath() {
    var a = DATA.arch;
    return 'M ' + a.left + ' ' + a.cy + ' A ' + a.r + ' ' + a.r + ' 0 0 1 ' + a.right + ' ' + a.cy +
      ' L ' + a.right + ' ' + a.bottom + ' L ' + a.left + ' ' + a.bottom + ' Z';
  }
  function reflectedName() { return REFLECTED.split('').reverse().join(''); }

  var VIEW = { x: -40, y: -40, w: 680, h: 920 };   // the SVG viewBox (frame and cartouche around the glass)
  var root = null, svg = null, canvas = null, ctx = null, ribbon = null, caption = null, speaker = null;
  var angle = 0, spin = 0.0016, drag = null, raf = null, visible = true, lastT = 0;

  /* ------------------------------------------------------------------ the kaleidoscope */
  // A handful of glass chips in one wedge; the wedge is drawn 12 times, every other one mirrored.
  var chips = [];
  function seedChips(count) {
    chips = [];
    var r = 1;
    for (var i = 0; i < count; i++) {
      r = (r * 16807) % 2147483647;
      var u = r / 2147483647; r = (r * 16807) % 2147483647;
      var v = r / 2147483647; r = (r * 16807) % 2147483647;
      var w = r / 2147483647;
      chips.push({ d: 0.12 + 0.82 * u, a: v * Math.PI / 6, s: 0.035 + 0.075 * w, k: i % GLASS.length, sides: 3 + (i % 3) });
    }
  }
  function drawKaleidoscope(t) {
    if (!ctx) return;
    var W = canvas.width, H = canvas.height;
    // the canvas has the SVG's aspect ratio, so one scale maps viewBox units onto it
    var k = W / VIEW.w, ox = -VIEW.x * k, oy = -VIEW.y * k;
    var cx = ox + DATA.impact[0] * k, cy = oy + DATA.impact[1] * k;
    // the radius that just reaches the farthest corner of the glass, so no chip is wasted outside it
    var a = DATA.arch;
    var R = k * Math.max(Math.hypot(DATA.impact[0] - a.left, DATA.impact[1] - (a.cy - a.r)), Math.hypot(DATA.impact[0] - a.right, DATA.impact[1] - (a.cy - a.r)),
      Math.hypot(DATA.impact[0] - a.left, a.bottom - DATA.impact[1]), Math.hypot(DATA.impact[0] - a.right, a.bottom - DATA.impact[1]));
    ctx.clearRect(0, 0, W, H);
    ctx.save();
    // the kaleidoscope only shows through the glass
    ctx.beginPath();
    ctx.moveTo(ox + a.left * k, oy + a.cy * k);
    ctx.arc(ox + a.cx * k, oy + a.cy * k, a.r * k, Math.PI, 2 * Math.PI);
    ctx.lineTo(ox + a.right * k, oy + a.bottom * k);
    ctx.lineTo(ox + a.left * k, oy + a.bottom * k);
    ctx.closePath();
    ctx.clip();
    ctx.fillStyle = '#0b0614';
    ctx.fillRect(0, 0, W, H);
    var have = owned().filter(Boolean).length;
    var wedge = Math.PI / 6;
    for (var s = 0; s < 12; s++) {
      ctx.save();
      ctx.translate(cx, cy);
      // odd wedges are mirror images: turn to the far edge of the wedge, then flip back over it
      if (s % 2) { ctx.rotate(angle + (s + 1) * wedge); ctx.scale(1, -1); } else ctx.rotate(angle + s * wedge);
      ctx.beginPath(); ctx.moveTo(0, 0); ctx.arc(0, 0, R, 0, wedge); ctx.closePath(); ctx.clip();
      for (var i = 0; i < chips.length; i++) {
        var c = chips[i];
        var aa = c.a + Math.sin(t / 2600 + i) * 0.06;
        var x = Math.cos(aa) * c.d * R, y = Math.sin(aa) * c.d * R, rr = c.s * R;
        ctx.beginPath();
        for (var p = 0; p < c.sides; p++) {
          var th = (p / c.sides) * Math.PI * 2 + i + t / 5200;
          ctx.lineTo(x + Math.cos(th) * rr, y + Math.sin(th) * rr);
        }
        ctx.closePath();
        ctx.globalAlpha = 0.3 + 0.05 * Math.min(have, 8);
        ctx.fillStyle = GLASS[(c.k + have) % GLASS.length];
        ctx.fill();
        ctx.globalAlpha = 0.5;
        ctx.strokeStyle = 'rgba(255, 244, 214, 0.35)';
        ctx.lineWidth = 1;
        ctx.stroke();
      }
      ctx.restore();
    }
    ctx.restore();
    ctx.globalAlpha = 1;
  }
  function frame(t) {
    raf = null;
    if (!root || !visible || document.hidden) return;
    var dt = lastT ? Math.min(64, t - lastT) : 16;
    lastT = t;
    if (!drag && !reducedMotion() && !complete()) angle += spin * dt / 16;
    drawKaleidoscope(t);
    if (!complete() && !reducedMotion()) raf = requestAnimationFrame(frame);
  }
  function kick() { if (!raf && root) raf = requestAnimationFrame(frame); }
  function sizeCanvas() {
    if (!canvas || !root) return;
    var r = svg.getBoundingClientRect();
    var dpr = Math.min(2, window.devicePixelRatio || 1);
    canvas.width = Math.max(1, Math.round(r.width * dpr));
    canvas.height = Math.max(1, Math.round(r.height * dpr));
    drawKaleidoscope(performance.now());
  }
  function complete() { return owned().every(Boolean); }

  /* ------------------------------------------------------------------ the mirror */
  function drawFrame(g) {
    var a = DATA.arch;
    var outer = 'M ' + (a.left - 34) + ' ' + a.cy + ' A ' + (a.r + 34) + ' ' + (a.r + 34) + ' 0 0 1 ' + (a.right + 34) + ' ' + a.cy +
      ' L ' + (a.right + 34) + ' ' + (a.bottom + 34) + ' L ' + (a.left - 34) + ' ' + (a.bottom + 34) + ' Z';
    el('path', { d: outer + ' ' + glassPath(), 'fill-rule': 'evenodd', fill: 'url(#sm-gold)', stroke: '#5a3d12', 'stroke-width': 2 }, g);
    el('path', { d: glassPath(), fill: 'none', stroke: '#fff1c1', 'stroke-opacity': 0.55, 'stroke-width': 1.5 }, g);
    el('path', { d: outer, fill: 'none', stroke: '#3b2508', 'stroke-width': 3 }, g);
    // carved scrolls along the frame
    for (var i = 0; i < 26; i++) {
      var th = Math.PI + Math.PI * (i + 0.5) / 26, rr = a.r + 17;
      var x = a.cx + rr * Math.cos(th), y = a.cy + rr * Math.sin(th);
      el('circle', { cx: x.toFixed(1), cy: y.toFixed(1), r: 4.2, fill: 'none', stroke: '#7a5419', 'stroke-width': 1.2 }, g);
    }
    for (var j = 0; j < 9; j++) {
      var yy = a.cy + (a.bottom - a.cy) * (j + 0.5) / 9;
      [a.left - 17, a.right + 17].forEach(function (xx) { el('circle', { cx: xx, cy: yy.toFixed(1), r: 4.2, fill: 'none', stroke: '#7a5419', 'stroke-width': 1.2 }, g); });
    }
    // the crest: the Mirror Speaker's signature, a single horizontal line under a small sun
    var top = a.cy - a.r - 34;
    el('path', { d: 'M ' + (a.cx - 46) + ' ' + (top + 4) + ' Q ' + a.cx + ' ' + (top - 54) + ' ' + (a.cx + 46) + ' ' + (top + 4) + ' Z', fill: 'url(#sm-gold)', stroke: '#5a3d12', 'stroke-width': 2 }, g);
    el('circle', { cx: a.cx, cy: top - 16, r: 8, fill: '#fff1c1', stroke: '#7a5419', 'stroke-width': 1.5 }, g);
    el('line', { x1: a.cx - 26, y1: top - 2, x2: a.cx + 26, y2: top - 2, stroke: '#3b2508', 'stroke-width': 2.5, 'stroke-linecap': 'round' }, g);
  }

  // A quill about 80 units long, drawn along the x axis from the nib (0, 0)
  function drawFeather(g) {
    el('path', { d: 'M 14 0 C 30 -13 60 -16 84 -3 C 66 5 36 11 14 0 Z', fill: 'url(#sm-gold)', stroke: '#5a3d12', 'stroke-width': 1.2 }, g);
    var barbs = el('g', { stroke: '#7a5419', 'stroke-width': 0.8, fill: 'none' }, g);
    [24, 36, 48, 60, 70].forEach(function (x) {
      el('path', { d: 'M ' + x + ' 0 L ' + (x + 7) + ' -8' }, barbs);
      el('path', { d: 'M ' + x + ' 0 L ' + (x + 6) + ' 5' }, barbs);
    });
    el('path', { d: 'M 0 0 L 84 -3', stroke: '#3b2508', 'stroke-width': 1.6, 'stroke-linecap': 'round', fill: 'none' }, g);
  }

  function render(flashNew) {
    if (!root) return;
    var have = owned();
    var count = have.filter(Boolean).length;
    var done = count === 9;
    var next = have.indexOf(false);
    svg.textContent = '';
    var defs = el('defs', null, svg);
    var gold = el('linearGradient', { id: 'sm-gold', x1: 0, y1: 0, x2: 1, y2: 1 }, defs);
    [['0', '#f7dc8c'], ['0.35', '#c99a3b'], ['0.6', '#8a5d1d'], ['1', '#e3b95c']].forEach(function (s) { el('stop', { offset: s[0], 'stop-color': s[1] }, gold); });
    var warm = el('radialGradient', { id: 'sm-warm', cx: '50%', cy: '62%', r: '70%' }, defs);
    [['0', '#4a2a18'], ['0.55', '#2a1430'], ['1', '#120a1c']].forEach(function (s) { el('stop', { offset: s[0], 'stop-color': s[1] }, warm); });
    var clip = el('clipPath', { id: 'sm-glass' }, defs);
    el('path', { d: glassPath() }, clip);

    // the glass: dark and see-through, so the kaleidoscope shows where fragments are missing
    var glass = el('g', { 'clip-path': 'url(#sm-glass)' }, svg);
    el('path', { d: glassPath(), fill: 'rgba(8, 4, 16, 0.18)' }, glass);
    DATA.shards.forEach(function (sh, i) {
      var g = el('g', {
        class: 'sm-shard' + (have[i] ? ' is-set' : ' is-missing') + (i === next ? ' is-next' : '') + (flashNew && flashNew.indexOf(i) >= 0 ? ' is-new' : ''),
        tabindex: '0', role: 'button', 'data-node': STATIONS[i].node,
        'aria-label': 'Fragment ' + sh.roman + ' · Station ' + STATIONS[i].station + ' · ' + STATIONS[i].room + (have[i] ? ' · set in the mirror' : (i === next ? ' · the next room' : ' · still missing'))
      }, glass);
      var shardClip = el('clipPath', { id: 'sm-shard-' + i }, defs);
      el('path', { d: pathOf(sh.points, true) }, shardClip);
      if (have[i]) {
        el('path', { d: pathOf(sh.points, true), fill: 'url(#sm-warm)' }, g);
        var lines = el('g', { 'clip-path': 'url(#sm-shard-' + i + ')', fill: 'none', stroke: '#f6e3b0', 'stroke-width': 1.6, 'stroke-linecap': 'round', 'stroke-linejoin': 'round', opacity: 0.92 }, g);
        DATA.facade.forEach(function (pl) { el('path', { d: pathOf(pl, false) }, lines); });
        el('path', { class: 'sm-sheen', d: pathOf(sh.points, true), fill: 'url(#sm-gold)', opacity: 0 }, g);
      } else {
        el('path', { d: pathOf(sh.points, true), fill: 'rgba(10, 6, 20, 0.35)' }, g);
        var c = sh.center;
        el('text', { x: c[0], y: c[1] + 7, 'text-anchor': 'middle', class: 'sm-roman' }, g).textContent = sh.roman;
      }
      el('path', { class: 'sm-edge', d: pathOf(sh.points, true), fill: 'none' }, g);
    });
    // the cracks over everything (the mended mirror keeps faint seams of gold)
    var cracks = el('g', { fill: 'none', stroke: done ? 'rgba(247, 220, 140, 0.45)' : 'rgba(235, 228, 255, 0.75)', 'stroke-width': done ? 1 : 1.4 }, glass);
    DATA.cracks.forEach(function (c) { el('path', { d: pathOf(c, false) }, cracks); });

    drawFrame(el('g', { 'aria-hidden': 'true' }, svg));
    // Once the first fragment is set, a small gilded feather lies on the sill of the frame. Nobody mentions it.
    if (have[0]) {
      drawFeather(el('g', { class: 'sm-feather', 'aria-hidden': 'true', transform: 'translate(548 852) rotate(-34)' }, svg));
      if (window.EclipseNotebook && window.EclipseNotebook.clue) window.EclipseNotebook.clue('feather');
    }

    // the cartouche under the glass
    var a = DATA.arch;
    var cart = el('g', { 'aria-hidden': 'true' }, svg);
    var cw = done ? 460 : 300;   // the name of the house is longer than the title of the mirror
    el('rect', { x: a.cx - cw / 2, y: a.bottom + 46, width: cw, height: 44, rx: 10, fill: 'url(#sm-gold)', stroke: '#5a3d12', 'stroke-width': 2 }, cart);
    el('text', { x: a.cx, y: a.bottom + 74, 'text-anchor': 'middle', class: 'sm-cartouche' }, cart).textContent = done ? reflectedName() : 'The Mirror of Tower III';

    if (caption) caption.textContent = done
      ? 'The mirror is whole. It reflects ' + reflectedName().replace(' · ', ', ') + '.'
      : count + ' of 9 fragments set' + (next >= 0 ? ' · next: ' + STATIONS[next].room + ' (Station ' + STATIONS[next].station + ')' : '');
    // the Mirror Speaker's line for the next room, written in the glass once its door is open (hub/js/mirror-speaker.js)
    if (speaker) {
      speaker.textContent = '';
      speaker.hidden = true;
      if (window.EclipseMirrorSpeaker && next >= 1 && !done) window.EclipseMirrorSpeaker.render(STATIONS[next].node, speaker);
    }
    root.classList.toggle('is-complete', done);
    renderRibbon(have, next);
    sizeCanvas();
    kick();
  }

  // The nine rooms in order, with Hermes's lantern at the next one
  function renderRibbon(have, next) {
    if (!ribbon) return;
    ribbon.textContent = '';
    STATIONS.forEach(function (s, i) {
      var b = document.createElement('button');
      b.type = 'button';
      b.className = 'sm-room' + (have[i] ? ' is-set' : '') + (i === next ? ' is-next' : '');
      b.setAttribute('data-node', String(s.node));
      b.title = 'Station ' + s.station + ' · ' + s.room;
      b.setAttribute('aria-label', 'Station ' + s.station + ' · ' + s.room + (have[i] ? ' · done' : (i === next ? ' · Hermes is heading here' : '')));
      b.textContent = DATA.shards[i].roman;
      ribbon.appendChild(b);
    });
  }

  function open(node) {
    if (typeof window.selectStageStation === 'function') window.selectStageStation(node);
  }

  function mount(container) {
    if (!container) return;
    if (root && root.parentNode === container) { refresh(); return; }
    container.textContent = '';
    root = document.createElement('div');
    root.className = 'stage-mirror';
    root.tabIndex = 0;
    root.setAttribute('role', 'group');
    root.setAttribute('aria-label', 'The Mirror of Tower III. Drag, or use the arrow keys, to turn the kaleidoscope behind the missing fragments. Choose a fragment to open its room.');
    canvas = document.createElement('canvas');
    canvas.className = 'stage-mirror-kaleido';
    canvas.setAttribute('aria-hidden', 'true');
    ctx = canvas.getContext('2d');
    svg = el('svg', { class: 'stage-mirror-svg', viewBox: VIEW.x + ' ' + VIEW.y + ' ' + VIEW.w + ' ' + VIEW.h, preserveAspectRatio: 'xMidYMid meet' });
    var stage = document.createElement('div');
    stage.className = 'stage-mirror-glass';
    stage.appendChild(canvas);
    stage.appendChild(svg);
    root.appendChild(stage);
    caption = document.createElement('p');
    caption.className = 'stage-mirror-caption';
    caption.setAttribute('aria-live', 'polite');
    root.appendChild(caption);
    speaker = document.createElement('div');
    speaker.className = 'stage-mirror-speaker';
    speaker.hidden = true;
    root.appendChild(speaker);
    ribbon = document.createElement('div');
    ribbon.className = 'stage-mirror-ribbon';
    ribbon.setAttribute('role', 'group');
    ribbon.setAttribute('aria-label', 'The nine rooms of Tower III');
    root.appendChild(ribbon);
    container.appendChild(root);

    seedChips(26);
    // turning the kaleidoscope: drag anywhere on the mirror, or the arrow keys
    stage.addEventListener('pointerdown', function (e) {
      if (e.target.closest && e.target.closest('.sm-shard.is-set')) return;
      drag = { x: e.clientX, a: angle, moved: false };
    });
    window.addEventListener('pointermove', function (e) {
      if (!drag) return;
      var dx = e.clientX - drag.x;
      if (Math.abs(dx) > 4) drag.moved = true;
      angle = drag.a + dx * 0.008;
      if (reducedMotion() || complete()) drawKaleidoscope(performance.now());
    });
    window.addEventListener('pointerup', function () { setTimeout(function () { drag = null; }, 0); });
    window.addEventListener('pointercancel', function () { setTimeout(function () { drag = null; }, 0); });
    root.addEventListener('keydown', function (e) {
      if (e.target !== root) return;
      if (e.key === 'ArrowLeft' || e.key === 'ArrowRight') {
        e.preventDefault();
        angle += (e.key === 'ArrowLeft' ? -1 : 1) * 0.12;
        drawKaleidoscope(performance.now());
      }
    });
    root.addEventListener('click', function (e) {
      if (drag && drag.moved) return;
      var t = e.target.closest && e.target.closest('[data-node]');
      if (t) open(parseInt(t.getAttribute('data-node'), 10));
    });
    root.addEventListener('keydown', function (e) {
      var t = e.target.closest && e.target.closest('.sm-shard');
      if (t && (e.key === 'Enter' || e.key === ' ')) { e.preventDefault(); open(parseInt(t.getAttribute('data-node'), 10)); }
    });
    window.addEventListener('resize', sizeCanvas);
    document.addEventListener('visibilitychange', function () { if (!document.hidden) { lastT = 0; kick(); } });
    if ('IntersectionObserver' in window) {
      new IntersectionObserver(function (entries) { visible = entries[0].isIntersecting; if (visible) { lastT = 0; kick(); } }).observe(root);
    }
    refresh();
  }

  // Redraws the mirror; a fragment that was not in place last time flashes once as it sets
  function refresh() {
    if (!root) return;
    var have = owned();
    var seen = parseInt(ls(SEEN_KEY) || '0', 10) || 0;
    var fresh = [];
    have.forEach(function (h, i) { if (h && !(seen & (1 << i))) fresh.push(i); });
    var mask = 0;
    have.forEach(function (h, i) { if (h) mask |= (1 << i); });
    try { localStorage.setItem(SEEN_KEY, String(mask)); } catch (e) {}
    render(fresh);
  }

  window.StageMirror = { mount: mount, refresh: refresh, stations: STATIONS, reflectedName: reflectedName };
})();
