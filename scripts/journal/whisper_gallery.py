#!/usr/bin/env python3
"""
The Whispering Gallery · the elliptical hall of the third tower (Stage Path, Station 22)
=========================================================================================
One source of truth for the plan of the gallery:
- an ellipse 10 varas long and 8 varas wide (half-axes 5 and 4), drawn the gardener's way: two pins and a string
  of 10 varas; the pins stand 3 varas either side of the middle (3, 4, 5), and they are the two foci,
- the colonnade along its wall and the door in the middle of the south side.

A whisper at one focus is heard at the other. The raiders whisper at the east focus; Silvia must stand at the
west one. Sheet 20B draws the ellipse, the string and the axes, but not the pins: she finds them with a ruler.
Used by the journal sheet (scripts/journal/build_stage_path.py) and by the Hub, which loads the generated
`web/assets/js/whisper-gallery-data.js`. Deterministic: running it twice writes the same file.

Plan coordinates are in varas: x grows to the east, y to the north, (0, 0) is the middle of the gallery.

Run:  python3 scripts/journal/whisper_gallery.py   (writes the Hub data and the room's thumbnail)
"""

import json
import math
import os

PROJECT_ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
OUT_JS = os.path.join(PROJECT_ROOT, "web", "assets", "js", "whisper-gallery-data.js")

A, B = 5.0, 4.0                         # half-axes in varas: the string is 2A = 10 varas long
C = math.sqrt(A * A - B * B)            # 3 varas: where the pins stood
COLUMNS = 18                            # around the wall, with the door in the place of the southmost one
COLUMN_R = 0.93                         # the columns stand just inside the wall
COLUMN_SIZE = 0.22                      # radius of a column, in varas
DOOR = (0.0, -B)                        # the door, in the middle of the south wall
RAIDERS = "east"                        # the focus where the raiders whisper; Silvia listens at the other


def build():
    cols = []
    for i in range(COLUMNS):
        t = -math.pi / 2 + 2 * math.pi * i / COLUMNS
        if i == 0:
            continue                    # t = -90 degrees: the door
        cols.append([round(A * COLUMN_R * math.cos(t), 3), round(B * COLUMN_R * math.sin(t), 3)])
    return {
        "a": A, "b": B, "c": C,
        "foci": {"west": [-C, 0.0], "east": [C, 0.0]},
        "raiders": RAIDERS,
        "door": list(DOOR),
        "columns": cols,
        "column_r": COLUMN_SIZE,
    }


def write_js(data):
    js = ("// GENERATED by scripts/journal/whisper_gallery.py · do not edit by hand.\n"
          "// The plan of the Whispering Gallery in varas (x east, y north): its ellipse, its two foci and its colonnade.\n"
          "window.WHISPER_GALLERY = " + json.dumps(data, separators=(",", ":")) + ";\n")
    os.makedirs(os.path.dirname(OUT_JS), exist_ok=True)
    with open(OUT_JS, "w", encoding="utf-8") as fh:
        fh.write(js)
    return OUT_JS


def thumbnail(data, path):
    """The card of the room on the Quest Map: the dark gallery from above, its columns, and faint ripples of whispers
    running along it (760 x 480). The foci are not marked: finding them is the game."""
    import cv2
    import numpy as np
    W, H, S = 760, 480, 4
    img = np.zeros((H * S, W * S, 3), np.uint8)
    img[:] = (16, 10, 14)
    k = 54 * S                                           # pixels per vara
    cx, cy = W * S // 2, H * S // 2
    P = lambda x, y: (int(round(cx + x * k)), int(round(cy - y * k)))
    glow = np.zeros(img.shape[:2], np.float32)
    cv2.ellipse(glow, (cx, cy), (int(data["a"] * k), int(data["b"] * k)), 0, 0, 360, 1.0, -1)
    glow = cv2.GaussianBlur(glow, (0, 0), 1.2 * k)
    img = (img.astype(np.float32) + glow[:, :, None] * np.array([26, 46, 62], np.float32)).clip(0, 255).astype(np.uint8)
    for s in (0.25, 0.45, 0.65, 0.82):                   # ripples of whispers along the hall
        cv2.ellipse(img, (cx, cy), (int(data["a"] * k * s), int(data["b"] * k * s)), 0, 0, 360, (70, 120, 160), S, cv2.LINE_AA)
    cv2.ellipse(img, (cx, cy), (int(data["a"] * k), int(data["b"] * k)), 0, 0, 360, (140, 200, 236), 3 * S, cv2.LINE_AA)
    cv2.ellipse(img, (cx, cy), (int(data["a"] * k) + 4 * S, int(data["b"] * k) + 4 * S), 0, 0, 360, (70, 110, 140), S, cv2.LINE_AA)
    for x, y in data["columns"]:
        cv2.circle(img, P(x, y), int(data["column_r"] * k), (46, 60, 72), -1, cv2.LINE_AA)
        cv2.circle(img, P(x, y), int(data["column_r"] * k), (150, 205, 236), 2 * S, cv2.LINE_AA)
    dx, dy = P(*data["door"])
    cv2.rectangle(img, (dx - int(0.45 * k), dy - 2 * S), (dx + int(0.45 * k), dy + 6 * S), (16, 10, 14), -1)
    img = cv2.resize(img, (W, H), interpolation=cv2.INTER_AREA)
    vignette = np.zeros((H, W), np.float32)
    cv2.circle(vignette, (W // 2, H // 2), int(H * 0.66), 1.0, -1)
    vignette = cv2.GaussianBlur(vignette, (0, 0), H * 0.18)
    img = (img.astype(np.float32) * (0.3 + 0.7 * vignette[:, :, None])).astype(np.uint8)
    cv2.imwrite(path, img, [cv2.IMWRITE_WEBP_QUALITY, 82])
    return path


if __name__ == "__main__":
    d = build()
    print("written:", write_js(d))
    print("written:", thumbnail(d, os.path.join(PROJECT_ROOT, "web", "assets", "thumbnails", "whispering_gallery_preview.webp")))
